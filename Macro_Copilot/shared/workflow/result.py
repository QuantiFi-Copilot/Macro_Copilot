"""shared.workflow.result — typed workflow output + lineage summary.

The ``WorkflowResult`` returned by the executor.  Carries:

  - the terminal artifact (typed; one of the closed-family
    artifact wrappers from ``shared.artifacts.types``)
  - the workflow-level lineage summary (human-readable; analog of
    the bridge's reverse-path lineage summary, extended to span
    multi-node DAGs)
  - all intermediate node artifacts keyed by node_id, for
    inspectability

Why not just return the terminal artifact directly
--------------------------------------------------
A workflow's terminal artifact already carries a structured
``Lineage`` chain that walks back through every node.  That's
sufficient for programmatic provenance.  But a human reading
the LLM's response wants a readable summary of what the workflow
did — "primitive A → align → diff → threshold" — without parsing
the structured lineage.  ``workflow_lineage_summary`` is that
summary, generated by the executor at the workflow boundary
(NOT by the operator/primitive layers, which are blind to the
workflow's existence).

The intermediate ``node_artifacts`` map is for callers that want
to inspect a specific node's output without re-running the
workflow.  Frozen (the whole result is frozen) so accidental
mutation through this map can't propagate.
"""

from __future__ import annotations

from typing import Any, Dict, Union

from pydantic import BaseModel, ConfigDict, Field

from shared.artifacts.types import (
    EventSet,
    Panel,
    ScalarMetric,
    Series,
    SeriesSet,
    WindowedPanel,
)


# Closed-family terminal artifact union — a DERIVED site of the canonical
# ``ARTIFACT_TYPE_NAMES`` (``shared/workflow/registry.py``); it must
# enumerate exactly that family.  The lock-step test
# ``tests/test_artifact_closed_family_lockstep.py`` asserts the two stay
# in sync (ART2/ART6) — the gate that catches a derived site drifting
# from the canonical enum in either direction.
TerminalArtifact = Union[
    Series, SeriesSet, EventSet, Panel, WindowedPanel, ScalarMetric,
]


class WorkflowResult(BaseModel):
    """The executor's return value for a successful workflow run.

    Fields
    ------
    workflow_id :
        Echo of the input workflow's ``workflow_id`` (for
        logging / round-trip identity).
    terminal_artifact :
        The typed artifact emitted by the workflow's terminal
        node.  Always one of the closed-family artifact wrappers.
    workflow_lineage_summary :
        Human-readable one-line summary of the DAG's execution
        path: ``"workflow <workflow_id>: <node_id> [→ <node_id>]*"``.
        Generated by the executor by walking the topologically-
        sorted node sequence.  Distinct from the terminal
        artifact's structured ``lineage`` chain (which is more
        granular: one ``LineageStep`` per primitive/operator call,
        including bridge-introduced ``PrimitiveStep``s).
    node_artifacts :
        All intermediate artifacts keyed by ``node_id``.  Includes
        the terminal artifact.  Frozen via the model config so
        mutation through this dict cannot propagate.
    """

    model_config = ConfigDict(
        frozen=True, extra="forbid", arbitrary_types_allowed=True,
    )

    workflow_id: str = Field(..., min_length=1)
    terminal_artifact: TerminalArtifact
    workflow_lineage_summary: str = Field(..., min_length=1)
    node_artifacts: Dict[str, Any] = Field(default_factory=dict)


__all__ = [
    "TerminalArtifact",
    "WorkflowResult",
]
